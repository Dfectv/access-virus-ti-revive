// The guard in front of the Virus (sendguard.h, round 0.8.27 T4): rule 2 says TI Revive never sends the multi
// header "Original Bank/Patch" (page 0x72 parameters 0-3; issue #7: 72 00 03 made a TI2 load Init into all 16
// parts at the next power-up) and never the DSP's private command status 0xF4 (E248). Until now that was an
// assumption about the code; now every message passes this check.
#include "check.h"
#include "device/sendguard.h"

using namespace vti;

static bool blocked(std::initializer_list<uint8_t> m)
{
    std::vector<uint8_t> v(m);
    return blocked_to_virus(v.data(), v.size());
}

TEST(sendguard_multi_header_is_blocked)
{
    CHECK(blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x00, 0x03, 0x05, 0xF7})); // Original Patch (issue #7)
    CHECK(blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x00, 0x02, 0x00, 0xF7})); // Original Bank
    CHECK(blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x00, 0x01, 0x00, 0xF7})); // Flags
    CHECK(blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x00, 0x00, 0x00, 0xF7}));
    CHECK(blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x40, 0x03, 0x05, 0xF7})); // any part byte
    CHECK(blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x00, 0x72, 0x00, 0x03, 0x05, 0xF7})); // any device id
}

TEST(sendguard_private_command_is_blocked)
{
    CHECK(blocked({0xF4}));
    CHECK(blocked({0xF4, 0x01}));
}

TEST(sendguard_everything_else_passes)
{
    CHECK(!blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x00, 0x04, 0x41, 0xF7})); // multi name character
    CHECK(!blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x05, 0x22, 0x05, 0xF7})); // part MIDI channel (start-up)
    CHECK(!blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x00, 0x1D, 0x00, 0xF7})); // panel part (start-up)
    CHECK(!blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x72, 0x00, 0x21, 0x05, 0xF7})); // program
    CHECK(!blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x73, 0x00, 0x03, 0x05, 0xF7})); // page 0x73 parameter 3
    CHECK(!blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x70, 0x00, 0x03, 0x05, 0xF7})); // page A parameter 3
    CHECK(!blocked({0xF0, 0x00, 0x20, 0x33, 0x01, 0x10, 0x11, 0x00, 0x00, 0x72, 0x00, 0x03, 0xF7})); // a dump
    CHECK(!blocked({0x90, 60, 100}));
    CHECK(!blocked({0xF8}));
    CHECK(!blocked({0xF5, 0x00, 0x00}));
    CHECK(!blocked({}));
}
