#!/usr/bin/env python3
"""gen_replay.py TRACE.log OUT.h - build the replay table for the IOCTL emulation from a vtihook trace.

For the static query IOCTLs (the driver returns state, the plugin sends nothing meaningful) the emulation
answers with what the original VirusUSB.sys 2.9.66 returned in the trace (findings E036). For 0x2200D0/D4
the first DWORD of the buffer selects a property, so entries are keyed by (code, selector).
Buffers longer than the tracer's dump limit (512 B) are recorded up to that limit; the rest is zero.
Run with: python3 -I scripts/gen_replay.py captures/trace/vtihook-1896.log src/wrapper/replay_table.h
"""
import re
import sys

STATIC = {0x220000, 0x220004, 0x22000C, 0x220010, 0x220014, 0x22004C, 0x220068, 0x220070, 0x22009C,
          0x2200A4, 0x2200B4, 0x2200B8, 0x2200BC, 0x2200D0, 0x2200D4}
SELECTOR = {0x2200D0, 0x2200D4}

lines = open(sys.argv[1], encoding="utf-8", errors="replace").read().splitlines()
table = {}  # (code, sel) -> (ret, bytes)
for i, l in enumerate(lines):
    m = re.search(r"IOCTL ([0-9a-f]{8}) h=\w+ in=\w+/(\d+) out=\w+/(\d+)", l)
    if not m:
        continue
    code = int(m.group(1), 16)
    if code not in STATIC:
        continue
    inb, outb, ret = [], [], None
    j = i + 1
    while j < len(lines) and re.search(r"^\s*\S+ t\d+\s+(->|in |out|ub )", lines[j]):
        x = lines[j].split(None, 2)[2]
        r = re.search(r"-> ok=(\d) ret=(\d+)", x)
        if r:
            ret = int(r.group(2)) if r.group(1) == "1" else None
        elif x.startswith("in "):
            inb.append(x)
        elif x.startswith("out"):
            outb.append(x)
        j += 1
    if ret is None:
        continue
    data = bytes(int(h, 16) for o in outb for h in o.split(": ", 1)[1].replace("...", "").split())
    sel = -1
    if code in SELECTOR and inb:
        sel = int(inb[0].split(": ", 1)[1].split()[0], 16)
    table.setdefault((code, sel), (ret, data))  # first answer wins

with open(sys.argv[2], "w") as f:
    f.write("// replay_table.h - GENERATED by scripts/gen_replay.py from a vtihook trace of VirusUSB.sys 2.9.66.\n")
    f.write("// Static IOCTL answers for the emulation (findings E036). Do not edit by hand.\n#pragma once\n#include <stdint.h>\n\n")
    f.write("typedef struct { uint32_t code; int32_t sel; uint32_t ret; uint32_t len; const uint8_t *data; } replay_entry;\n\n")
    for k, ((code, sel), (ret, data)) in enumerate(sorted(table.items())):
        body = ", ".join("0x%02x" % b for b in data) or "0"
        f.write("static const uint8_t replay_%d[] = {%s};\n" % (k, body))
    f.write("\nstatic const replay_entry REPLAY[] = {\n")
    for k, ((code, sel), (ret, data)) in enumerate(sorted(table.items())):
        f.write("    {0x%06x, %d, %d, %d, replay_%d},\n" % (code, sel, ret, len(data), k))
    f.write("};\n")
print("%d entries -> %s" % (len(table), sys.argv[2]))
for (code, sel), (ret, data) in sorted(table.items()):
    print("  %06x sel=%3d ret=%6d recorded=%d" % (code, sel, ret, len(data)))
